export function convertDefToExercise(def: GymExerciseDef, customDetail?: string): Exercise {
  return {
    name: def.name,
    detail: customDetail || `${def.defaultSets} × ${def.defaultReps} · ${def.defaultRestSec} s repos`,
  };
}
